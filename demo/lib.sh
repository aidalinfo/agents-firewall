# ---------------------------------------------------------------------------------------------------
# Scenario results: each scenario calls scenario_begin, evidence..., then pass / fail / skip.
# ---------------------------------------------------------------------------------------------------
SCENARIO_ID=""; SCENARIO_TITLE=""; SCENARIO_T0=0; EVIDENCE_FILE=""
scenario_begin() {
  SCENARIO_ID="$1"; SCENARIO_TITLE="$2"; SCENARIO_T0="$(now_ms)"
  EVIDENCE_FILE="$RESULTS_DIR/$SCENARIO_ID.evidence"; : >"$EVIDENCE_FILE"
  printf '\n=== %s — %s\n' "$SCENARIO_ID" "$SCENARIO_TITLE" >&2
}
evidence() { printf '%s\n' "$*" >>"$EVIDENCE_FILE"; printf '  %s· %s%s\n' "$C_DIM" "$*" "$C_OFF" >&2; }
scenario_end() { # scenario_end <PASS|FAIL|SKIP> <message>
  local status="$1" msg="$2" dur
  dur=$(( ($(now_ms) - SCENARIO_T0) ))
  jqx -n --arg id "$SCENARIO_ID" --arg title "$SCENARIO_TITLE" --arg status "$status" --arg msg "$msg" \
    --argjson ms "$dur" --arg at "$(now_iso)" --rawfile ev "$EVIDENCE_FILE" \
    '{id: $id, title: $title, status: $status, message: $msg, duration_ms: $ms, at: $at,
      evidence: ($ev | split("\n") | map(select(length > 0)))}' >"$RESULTS_DIR/$SCENARIO_ID.json"
  case "$status" in
    PASS) printf '%sPASS%s %s — %s (%d ms)\n' "$C_GRN" "$C_OFF" "$SCENARIO_ID" "$msg" "$dur" ;;
    SKIP) printf '%sSKIP%s %s — %s\n' "$C_YEL" "$C_OFF" "$SCENARIO_ID" "$msg" ;;
    *) printf '%sFAIL%s %s — %s (%d ms)\n' "$C_RED" "$C_OFF" "$SCENARIO_ID" "$msg" "$dur" ;;
  esac
  [ "$status" != FAIL ]
}
pass() { scenario_end PASS "$1"; exit 0; }
fail() { scenario_end FAIL "$1"; exit 1; }
skip() { scenario_end SKIP "$1"; exit 0; }
# require_demo: the stack must be up (demo/up.sh), else SKIP with the reason.
require_demo() {
  api_healthy || skip "API not reachable on $AFW_API_URL (run demo/up.sh)"
  local s; for s in gateway exfil fake-llm allowed-api "$@"; do
    [ -n "$(dc ps -q --status running "$s" 2>/dev/null)" ] || skip "service $s is not running (run demo/up.sh)"
  done
}
# attempt <agent> <label> <command>: runs a bypass attempt in an agent, records exit code and output.
attempt() {
  local out rc=0
  out="$(agent_sh "$1" "$3" 2>&1)" || rc=$?
  evidence "$2: exit $rc, $(printf '%s' "$out" | tr '\n' ' ' | cut -c1-200)"
  return 0
}
# http_code_cmd <curl args...>: shell command (run in an agent) printing the HTTP status of a request. Through
# the explicit proxy an HTTPS denial happens on CONNECT (curl's http_code is then 000): the CONNECT status is
# printed instead.
http_code_cmd() {
  printf '%s' "curl -s -o /dev/null -w '%{http_code} %{http_connect}' --max-time 10 $* | awk '{print (\$1 == \"000\" && \$2 != \"000\") ? \$2 : \$1}'"
}
# positive_control <agent>: an allowed destination must work, otherwise a "blocked" result means nothing.
positive_control() {
  local out m
  m="ctl-$(rand_hex)"
  out="$(agent_sh "$1" "curl -sS --max-time 10 https://allowed.example/zen?m=$m" 2>&1)" ||
    fail "positive control failed ($1 cannot reach allowed.example: $out) — the demo network is broken"
  assert_received allowed-api "$m" "the positive control request"
  evidence "positive control: $1 -> allowed.example received ($m)"
}
