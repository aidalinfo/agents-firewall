//! Links from this lot to the neighbouring modules: the gateway protocol needs the installed
//! policy (policy module, lot L7a) and hands events, commands and captures to the logs module
//! (lot L7b); enrollments create agents through the policy module.
//!
//! The implementations are plugged into [`crate::AppState::ports`]. Until they are wired,
//! [`Unwired`] answers "nothing installed / nothing pending" for reads and refuses writes, so a
//! gateway keeps its last policy (or denies everything) and retries its events later.

use std::sync::Arc;

use afw_core::InstalledPolicy;
use afw_core::api::EnrollmentRequest;
use afw_core::events::GatewayEvent;
use afw_core::policy::{Agent, PolicyDocument};
use afw_core::protocol::{GatewayCommand, PolicyAck};
use futures::future::BoxFuture;
use uuid::Uuid;

use crate::AppState;
use crate::auth::Principal;
use crate::error::ApiError;

pub type PortFuture<'a, T> = BoxFuture<'a, Result<T, ApiError>>;

/// Policy module (lot L7a): `crate::policy::install::{installed_policy_for, record_install_ack}`
/// and `crate::policy::agents::create_agent`.
pub trait PolicyPort: Send + Sync {
    /// Policy the gateway should run (its desired revision), `None` when nothing is installed.
    fn installed_policy_for<'a>(
        &'a self,
        state: &'a AppState,
        gateway_id: Uuid,
    ) -> PortFuture<'a, Option<InstalledPolicy>>;
    /// Installation result reported by the gateway.
    fn record_install_ack<'a>(
        &'a self,
        state: &'a AppState,
        gateway_id: Uuid,
        ack: PolicyAck,
    ) -> PortFuture<'a, ()>;
    /// Currently published policy (MCP agent scope, `/me`), `None` when none is published.
    fn current_policy<'a>(&'a self, state: &'a AppState) -> PortFuture<'a, Option<PolicyDocument>>;
    /// Creates the agent in `session_id` (or a new session) and returns it with the session.
    /// The implementation enforces the session rules and EF-51 for the MCP agent.
    fn create_agent<'a>(
        &'a self,
        state: &'a AppState,
        principal: &'a Principal,
        session_id: Option<Uuid>,
        request: &'a EnrollmentRequest,
    ) -> PortFuture<'a, (Agent, Uuid)>;
}

/// Logs module (lot L7b): `crate::logs::{ingest_gateway_events, pending_commands}` and capture
/// storage.
pub trait LogsPort: Send + Sync {
    fn ingest_gateway_events<'a>(
        &'a self,
        state: &'a AppState,
        gateway_id: Uuid,
        events: Vec<GatewayEvent>,
    ) -> PortFuture<'a, ()>;
    /// Commands generated by the logs module (captures), delivered once.
    fn pending_commands<'a>(
        &'a self,
        state: &'a AppState,
        gateway_id: Uuid,
    ) -> PortFuture<'a, Vec<GatewayCommand>>;
    /// Finished pcap uploaded by the gateway.
    fn store_capture<'a>(
        &'a self,
        state: &'a AppState,
        gateway_id: Uuid,
        capture_id: Uuid,
        data: bytes::Bytes,
    ) -> PortFuture<'a, ()>;
}

/// Placeholder implementation used until the neighbouring modules are wired.
#[derive(Clone, Copy, Debug, Default)]
pub struct Unwired;

fn not_wired(what: &str) -> ApiError {
    ApiError::Internal(format!("{what} is not wired yet"))
}

impl PolicyPort for Unwired {
    fn installed_policy_for<'a>(
        &'a self,
        _: &'a AppState,
        _: Uuid,
    ) -> PortFuture<'a, Option<InstalledPolicy>> {
        Box::pin(async { Ok(None) })
    }
    fn record_install_ack<'a>(
        &'a self,
        _: &'a AppState,
        _: Uuid,
        _: PolicyAck,
    ) -> PortFuture<'a, ()> {
        Box::pin(async { Err(not_wired("policy install acknowledgement")) })
    }
    fn current_policy<'a>(&'a self, _: &'a AppState) -> PortFuture<'a, Option<PolicyDocument>> {
        Box::pin(async { Ok(None) })
    }
    fn create_agent<'a>(
        &'a self,
        _: &'a AppState,
        _: &'a Principal,
        _: Option<Uuid>,
        _: &'a EnrollmentRequest,
    ) -> PortFuture<'a, (Agent, Uuid)> {
        Box::pin(async { Err(not_wired("agent creation")) })
    }
}

impl LogsPort for Unwired {
    fn ingest_gateway_events<'a>(
        &'a self,
        _: &'a AppState,
        _: Uuid,
        _: Vec<GatewayEvent>,
    ) -> PortFuture<'a, ()> {
        Box::pin(async { Err(not_wired("event ingestion")) })
    }
    fn pending_commands<'a>(
        &'a self,
        _: &'a AppState,
        _: Uuid,
    ) -> PortFuture<'a, Vec<GatewayCommand>> {
        Box::pin(async { Ok(vec![]) })
    }
    fn store_capture<'a>(
        &'a self,
        _: &'a AppState,
        _: Uuid,
        _: Uuid,
        _: bytes::Bytes,
    ) -> PortFuture<'a, ()> {
        Box::pin(async { Err(not_wired("capture storage")) })
    }
}

/// The ports plugged into the application state.
#[derive(Clone)]
pub struct Ports {
    pub policy: Arc<dyn PolicyPort>,
    pub logs: Arc<dyn LogsPort>,
}

impl Default for Ports {
    fn default() -> Self {
        Self {
            policy: Arc::new(Unwired),
            logs: Arc::new(Unwired),
        }
    }
}
