# cli_has <subcommand...>: the CLI image exists and implements this subcommand (non-empty help).
cli_has() {
  [ "${AFW_DEMO_NO_CLI:-0}" = 1 ] && return 1
  image_exists "$AFW_CLI_IMAGE" || return 1
  local out
  out="$(docker run --rm "$AFW_CLI_IMAGE" "$@" --help 2>/dev/null)" || return 1
  [ -n "$out" ]
}

