# Mapping from the fixed ids of demo/policy/demo-policy.json to the ids returned by the API.
IDS_FILE="$STATE_DIR/ids.json"
demo_id() { # demo_id <demo uuid> -> real uuid
  [ -s "$IDS_FILE" ] || { printf '%s' "$1"; return; }
  jqx -r --arg k "$1" '.[$k] // $k' "$IDS_FILE"
}
did() { printf '00000000-0000-4000-8000-%012d' "$1"; }   # did 621 -> fixed demo id of rule 621

# create_resource <collection> <json with demo ids>: POSTs (the contract requires the client to send `id`),
# rewrites references to resources whose id differs, and records the id returned by the API.
create_resource() {
  local coll="$1" json="$2" demo new map body
  [ -s "$IDS_FILE" ] || echo '{}' >"$IDS_FILE"
  map="$(cat "$IDS_FILE")"
  demo="$(printf '%s' "$json" | jqx -r '.id')"
  body="$(printf '%s' "$json" | jqx -c --argjson m "$map" 'walk(if type == "string" and $m[.] then $m[.] else . end)')"
  new="$(api_post "/$coll" "$body" | jqx -r '.id')" || return 1
  record_id "$demo" "$new"
}
record_id() { jqx --arg k "$1" --arg v "$2" '. + {($k): $v}' "$IDS_FILE" >"$IDS_FILE.tmp" && mv "$IDS_FILE.tmp" "$IDS_FILE"; }
# enroll_hermes_agent <Agent json with demo ids> <gateway id>: POST /enrollments (EnrollmentRequest) creates the
# agent and its plugin token (role agent_plugin), then PUT completes it (addresses, labels, mcp_admin).
# The plugin token is written to demo/.state/demo.env (0600) for daniel-bot.
enroll_hermes_agent() {
  local json="$1" gw="$2" map body res id tok
  map="$(cat "$IDS_FILE")"
  json="$(printf '%s' "$json" | jqx -c --argjson m "$map" 'walk(if type == "string" and $m[.] then $m[.] else . end)')"
  body="$(printf '%s' "$json" | jqx -c --arg g "$gw" '{gateway_id: $g, kind: .kind, name: .name, zone_id: .zone_id, hermes: true}')"
  res="$(api_post /enrollments "$body")" || return 1
  id="$(printf '%s' "$res" | jqx -r '.agent.id')"
  tok="$(printf '%s' "$res" | jqx -r '.plugin_token // empty')"
  api_put "/agents/$id" "$(printf '%s' "$json" | jqx -c --arg id "$id" --arg g "$gw" '.id = $id | .gateway_id = $g')" >/dev/null || return 1
  record_id "$(printf '%s' "$1" | jqx -r '.id')" "$id"
  if [ -n "$tok" ]; then
    (umask 077; printf 'AFW_DEMO_DANIEL_TOKEN=%s\n' "$tok" >"$STATE_DIR/demo.env")
    AFW_DEMO_DANIEL_TOKEN="$tok"; export AFW_DEMO_DANIEL_TOKEN
  else
    warn "no plugin token returned for $(printf '%s' "$json" | jqx -r .name)"
  fi
}
# load_policy <PolicyDocument json file> [gateway id]: creates every resource of the document in the open
# session. Hermes agents are created through /enrollments when a gateway id is given.
load_policy() {
  local f="$1" gw="${2:-}" kind line coll
  echo '{}' >"$IDS_FILE"
  # Order respects references: zones, plain objects, groups, services, data classes, agents, rules.
  for kind in "zones:.zones[]" "objects:.objects[] | select(.spec.type != \"group\")" \
    "objects:.objects[] | select(.spec.type == \"group\")" "services:.services[]" \
    "data-classes:.data_classes[]" "agents:.agents[]" "rules:.rules | sort_by(.layer.type != \"baseline\", .position)[]" \
    "inspection-rules:.inspection_rules[]"; do
    jqx -c "${kind#*:}" "$f" | while IFS= read -r line; do
      coll="${kind%%:*}"
      step "create $coll: $(printf '%s' "$line" | jqx -r '.name')"
      if [ "$coll" = agents ] && [ -n "$gw" ] && printf '%s' "$line" | jqx -e '.hermes' >/dev/null; then
        enroll_hermes_agent "$line" "$gw" || die "cannot enroll $(printf '%s' "$line" | jqx -r .name)"
      else
        # Every demo agent sits behind the demo gateway (shown on the gateway page).
        if [ "$coll" = agents ] && [ -n "$gw" ]; then line="$(printf '%s' "$line" | jqx -c --arg g "$gw" '.gateway_id = $g')"; fi
        create_resource "$coll" "$line" || die "cannot create $coll $(printf '%s' "$line" | jqx -r .name)"
      fi
    done
  done
}
