# session_open: opens a policy session and exports AFW_SESSION_ID.
session_open() {
  local s
  if cli_has session open; then
    s="$(afw session open --json | jqx -r '.id')"
  else
    s="$(api_post /sessions | jqx -r '.id')"
  fi
  [ -n "$s" ] && [ "$s" != null ] || die "cannot open a policy session"
  AFW_SESSION_ID="$s"; export AFW_SESSION_ID
}
session_discard() {
  [ -n "$AFW_SESSION_ID" ] || return 0
  api_post "/sessions/$AFW_SESSION_ID/discard" >/dev/null || true
  AFW_SESSION_ID=""
}
# publish <comment>: publishes the open session, prints the new revision number.
publish() {
  local comment="$1" rev
  if cli_has publish; then
    rev="$(afw publish --comment "$comment" --json | jqx -r '.number // .revision.number')"
  else
    rev="$(api_post "/sessions/$AFW_SESSION_ID/publish" "$(jqx -nc --arg c "$comment" '{comment: $c}')" | jqx -r '.number')"
  fi
  AFW_SESSION_ID=""
  [ -n "$rev" ] && [ "$rev" != null ] || die "publish failed"
  printf '%s' "$rev"
}
# install <revision>: installs a revision on every gateway.
install() {
  if cli_has install; then afw install --revision "$1" --json >/dev/null
  else api_post /installs "$(jqx -nc --argjson r "$1" '{revision: $r, gateways: []}')" >/dev/null; fi
}
gateways_json() { api_get /gateways | items; }
gateway_id() { gateways_json | jqx -r --arg n "$1" 'select(.name == $n) | .id' | head -n1; }
# wait_installed <revision> [timeout s]: every gateway reports this active revision.
wait_installed() {
  local rev="$1" t="${2:-60}" i
  for i in $(seq 1 "$t"); do
    if gateways_json | jqx -s -e --argjson r "$rev" 'length > 0 and all(.[]; .active_revision == $r)' >/dev/null 2>&1; then
      return 0
    fi
    sleep 1
  done
  return 1
}
latest_revision() { api_get /revisions | items | jqx -s -r 'map(.number) | max // empty'; }
# publish_and_install <comment>: publish + install + wait, prints the revision.
publish_and_install() {
  local rev; rev="$(publish "$1")"
  install "$rev"
  wait_installed "$rev" "${2:-60}" || die "revision $rev not active on the gateways"
  printf '%s' "$rev"
}

