# api <METHOD> <path below /api/v1> [json body] : prints the response body; returns 1 on HTTP >= 400
# (problem+json printed on stderr). The last HTTP status is kept in $STATE_DIR/last_status.
api() {
  local method="$1" path="$2" body="${3:-}" out status
  [ -n "$AFW_TOKEN" ] || die "no API token (demo/.state/secrets.env is created by demo/up.sh)"
  local args=(-sS -X "$method" -H "Authorization: Bearer $AFW_TOKEN" -H "Accept: application/json" -H "X-Afw-Interface: $AFW_INTERFACE"
    -o "$STATE_DIR/last_body" -w '%{http_code}' --max-time "${AFW_API_TIMEOUT:-30}")
  if [ -n "$AFW_SESSION_ID" ] && [ -n "$AFW_SESSION_HEADER" ]; then args+=(-H "$AFW_SESSION_HEADER: $AFW_SESSION_ID"); fi
  if [ -n "$body" ]; then args+=(-H "Content-Type: application/json" --data-binary "$body"); fi
  status="$(curl "${args[@]}" "$AFW_API_URL$API$path" || echo 000)"
  echo "$status" >"$STATE_DIR/last_status"
  out="$(cat "$STATE_DIR/last_body" 2>/dev/null || true)"
  if [ "$status" -ge 400 ] || [ "$status" = 000 ]; then
    printf 'API %s %s -> HTTP %s %s\n' "$method" "$path" "$status" "$out" >&2
    return 1
  fi
  printf '%s' "$out"
}
api_get() { api GET "$@"; }
api_post() { api POST "$@"; }
api_put() { api PUT "$@"; }
api_patch() { api PATCH "$@"; }
api_delete() { api DELETE "$@"; }
last_status() { cat "$STATE_DIR/last_status" 2>/dev/null || echo 000; }
# Items of a list response, whether it is a bare array or a Page { items, next_cursor }.
items() { jqx -c 'if type == "array" then .[] else (.items // [])[] end'; }

api_healthy() { curl -fsS --max-time 3 "$AFW_API_URL/healthz" >/dev/null 2>&1; }
wait_api() {
  local i
  for i in $(seq 1 "${1:-90}"); do api_healthy && return 0; sleep 1; done
  return 1
}

