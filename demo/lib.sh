image_exists() { docker image inspect "$1" >/dev/null 2>&1; }
# agent_sh <service> <shell command>: run a command inside an agent container (as the agent).
agent_sh() { dc exec -T "$1" sh -c "$2"; }
# read_upstream_log <service> <file>: copies what a fake upstream received (JSON lines) into <file>.
# Returns non-zero if the log cannot be read (container down, volume missing): never treated as "nothing".
read_upstream_log() {
  dc exec -T "$1" sh -c "test -d /data && test -w /data && { cat /data/$1.jsonl 2>/dev/null || true; }" >"$2"
}
# assert_not_received <service> <marker> <what>: proof of non-reception; any read failure fails the scenario.
assert_not_received() {
  local f="$STATE_DIR/upstream-$1.log"
  read_upstream_log "$1" "$f" || fail "cannot read the receipt log of $1: no proof of non-reception"
  if grep -q -- "$2" "$f"; then fail "$3 reached $1"; fi
  evidence "$1 received nothing for $2 ($(wc -l <"$f" | tr -d ' ') requests in its log)"
}
# assert_received <service> <marker> <what>
assert_received() {
  local f="$STATE_DIR/upstream-$1.log"
  read_upstream_log "$1" "$f" || fail "cannot read the receipt log of $1"
  grep -q -- "$2" "$f" || fail "$3 did not reach $1"
}

# jq on the host when available, else in the tools image.
jqx() {
  if command -v jq >/dev/null 2>&1; then jq "$@"
  else docker run --rm -i afw-demo-tools:local jq "$@"; fi
}

